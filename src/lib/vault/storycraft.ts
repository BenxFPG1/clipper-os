export const STORYCRAFT = `=== STORYCRAFT: HOE EEN MINI-VERHAAL WERKT ===

DE KERN — belofte en inlossing:
- Elke clip is een contract met de kijker: de hook doet een belofte, de payoff lost hem in. Alles ertussen verdient het wachten.
- De kijker blijft niet voor informatie maar voor onopgeloste spanning. Open een vraag die pas aan het einde dichtgaat (open loop). Beantwoord je hem halverwege, dan is dat het echte einde van je clip.
- Maximaal één centrale spanningslijn per clip. Twee verhalen in één clip is nul verhalen.

CAUSALITEIT — "maar" en "dus", nooit "en toen":
- Zwak verhaal: dit gebeurde, en toen dit, en toen dit. Sterk verhaal: dit gebeurde, MAAR toen dit, DUS dit.
- Toets elke overgang tussen shots: kun je er "maar" of "dus" tussen zetten? Zo niet, dan is het een opsomming en moet er iets weg of anders geordend.

ESCALATIE — spanning is een trap, geen vlakte:
- Elke stap moet groter, gekker of pijnlijker zijn dan de vorige. Herhaal nooit hetzelfde niveau twee keer.
- Orden op spanningscurve, niet op chronologie. Het beste materiaal van minuut 3 mag na dat van minuut 30 komen als de curve dat vraagt.
- De één-na-laatste beat is de donkerste of gekste; direct daarna de payoff. Niets meer erna behalve eventueel één korte button (uitsmijter die de payoff nog één keer raakt).

DE HOOK — binnen 1,5 seconde:
- Begin mid-actie of mid-zin. Context komt daarna, nooit ervoor.
- De sterkste hooks zijn specifiek: een concreet detail ("een Hema-bh"), een vonnis zonder context, een getal dat niet kan kloppen. Vaagheid ("dit geloof je nooit") is een lege belofte.
- De hook toont of belooft het hoogtepunt zonder het weg te geven: wel de explosie laten zien, niet wie hem veroorzaakte.

STAKES — waarom zou iemand dit iets kunnen schelen:
- Zonder inzet geen spanning. Maak expliciet wat er voor iemand op het spel staat: reputatie, geld, gelijk krijgen, gezichtsverlies.
- Personen dragen verhalen, onderwerpen niet. Eén persoon als anker; zijn of haar boog is de clip.

DE PAYOFF:
- Moet het letterlijke antwoord zijn op de belofte van de hook, en groter aanvoelen dan verwacht — via de opgebouwde context, niet via overdrijving.
- Knip nooit vóór de payoff af, en loop nooit door erna. Elke seconde na de payoff kost kijkers die de clip bijna hadden afgemaakt.

VEELGEMAAKTE FOUTEN (herken en herstel):
- Opsomming vermomd als verhaal: shots die verwisselbaar zijn van volgorde. Als je twee shots kunt omdraaien zonder dat er iets breekt, is er geen causaliteit.
- De belofte breken: hook over X, payoff over Y. De kijker voelt zich bedrogen en het algoritme ziet het aan de retentie.
- Te vroeg geruststellen: spanning oplossen in het midden "zodat het klopt". Klopt het te vroeg, dan is het klaar te vroeg.
- Context vooraan: eerst uitleggen wie iedereen is. Niemand wacht daarop; identiteit blijkt onderweg.`;

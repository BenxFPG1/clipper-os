/**
 * Taal voor de mond en het oor — de laag die ontbrak tussen "goede structuur"
 * en "goed script".
 *
 * De storycraft-vault zegt hoe een verhaal wérkt; deze laag zegt hoe het
 * klínkt. De scripts die de agent schreef hadden nette spanningsbogen maar
 * lazen als geschreven Nederlands: te lange zinnen, aankondigingen in plaats
 * van beelden, en meer woorden per shot dan een mond in die seconden kwijt
 * kan. Dat verschil hoor je in elke seconde van de video, en het is exact het
 * verschil tussen een script dat "klopt" en een script dat werkt.
 */
export const SPREEKTAAL = `=== SPREEKTAAL: SCHRIJVEN VOOR DE MOND EN HET OOR ===

HET TEMPO IS EEN HARDE GRENS:
- Gesproken Nederlands haalt 2,5 tot 3 woorden per seconde. Een shot van 4 seconden draagt dus hooguit 11 woorden — niet 25. Tel je woorden per shot; past het niet, dan schrap je, want de spreker kan niet sneller en de editor kan er niets van maken.
- Eén gedachte per zin. Een zin die je niet in één adem kunt zeggen, is er twee.
- Zinnen onder de 12 woorden. Wissel kort en heel kort af; drie lange zinnen achter elkaar is een luisterdip.

SCHRIJF ZOALS MENSEN PRATEN:
- Lees elke zin hardop (in je hoofd) vóór je hem opschrijft. Struikel je, dan struikelt de spreker ook.
- Werkwoorden vooraan de betekenis, geen tangconstructies, geen bijzinnen in bijzinnen. "Hij verloor alles" verslaat "waarbij uiteindelijk alles verloren ging".
- Geen schrijftaalwoorden: "echter", "tevens", "middels", "waarbij", "desalniettemin" bestaan niet in spraak.
- Spreek de kijker aan met "je". Eén kijker, niet een publiek.
- Het krachtwoord staat aan het éínd van de zin. "Twee jaar heeft niemand het geweten" is zwakker dan "niemand wist het — twee jaar lang".

TOON, VERTEL NIET AAN (de doodzonde-lijst):
- NOOIT aankondigen wat er gaat komen: "kijk mee", "let op wat er gebeurt", "je gelooft nooit wat er dan gebeurt", "wacht tot het einde". De aankondiging ís geen spanning; hij bekent dat de spanning er nog niet staat.
- NOOIT sociale bewijskracht verzinnen: "de comments ontploften", "iedereen had het erover", "dit ging viral" — tenzij het aantoonbaar waar is en in de briefing staat.
- NOOIT genummerde bewijskaarten ("BEWIJS 1", "FEIT 3"): dat is een opsomming die zich als verhaal verkleedt.
- NOOIT een placeholder: elk woord in het script moet zó uitgesproken kunnen worden. "[FRAGMENT A]" of "[het detail]" is geen script maar een smoes. Ken je het bronmateriaal niet, bouw dan een script dat volledig op eigen tekst draait — of zeg in "benodigdheden" precies welk fragment er nog gekozen moet worden, buiten de gesproken tekst om.

DE SPECIFICITEITSLADDER (elke trede omhoog is retentie):
- abstract -> categorie -> ding -> ding met detail. "Iets kopen" -> "kleding" -> "een bh" -> "een Hema-bh van 12,95".
- Getallen precies: "12.000 euro" verslaat "veel geld"; "veertig seconden eerder" verslaat "even daarvoor".
- Eigennamen, merknamen, tijdstippen en plaatsen zijn gratis geloofwaardigheid. Elke vage aanduiding die je specifiek kunt maken, maak je specifiek.

RE-HOOKS — de belofte onderweg vernieuwen:
- De hook koopt 3 seconden; daarna moet de clip zichzelf elke 7 à 10 seconden opnieuw verkopen. Niet met een aankondiging, maar met een wending, een nieuw concreet detail, of een half antwoord dat een grotere vraag opent.
- De beste re-hook is een zin die de vorige beat afmaakt én de volgende opent: "Dat klopte. Tot de bank belde."
- Plan re-hooks op de uitvalzones (rond 30%, 50%, 70% van de clip) — daar hoort net iets nieuws open te staan.

DE SCREENSHOTZIN:
- Elke clip verdient één zin die op zichzelf deelbaar is: kort, stellig, licht overdreven waar, en zonder context te begrijpen. Dat is de zin die gequoot wordt in comments en stitches.
- Schrijf hem bewust en leg hem op de payoff of de button — nooit in de setup, daar is hij verspild.

HET SLOT:
- De laatste zin is de tweede belangrijkste van het script (na de hook). Geen uitleg, geen samenvatting, geen "dus dat was het" — een button die de payoff nog één keer raakt, of een vraag die de kijker in de comments beantwoordt.
- Comment-vragen zijn binair of invulbaar ("Wat had jij gedaan?" / "Team A of team B?"), geen open essays.`;
